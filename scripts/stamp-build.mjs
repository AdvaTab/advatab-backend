import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));

function git(args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return null;
  }
}

const gitStatus = git(['status', '--porcelain', '--untracked-files=normal']);
const buildInfo = {
  component: 'backend',
  version,
  buildDate: new Date().toISOString(),
  commit: git(['rev-parse', 'HEAD']),
  dirty: gitStatus === null ? null : gitStatus.length > 0,
};

await writeFile(resolve(root, 'src/build-info.generated.ts'),
  `// Generated by scripts/stamp-build.mjs. Do not edit.\nexport const buildInfo = ${JSON.stringify(buildInfo)} as const;\n`);
